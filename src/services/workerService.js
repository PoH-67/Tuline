export const getWorkerById = (id) => {
  return WORKERS.find((w) => w.id === id) || WORKERS[0];
};

export const getWorkersByCategory = (categoryKey) => {
  if (!categoryKey || categoryKey === 'semua') return WORKERS;
  const key = categoryKey.toLowerCase();
  return WORKERS.filter(
    (w) =>
      w.categoryKey.toLowerCase() === key ||
      (w.categories && w.categories.includes(key)) ||
      w.category.toLowerCase().includes(key)
  );
};
