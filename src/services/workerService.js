export function getWorkerById(id) {
  return WORKERS.find((w) => w.id === id);
}

export function getWorkersByCategory(catKey) {
  if (!catKey || catKey === 'semua') return WORKERS;
  const k = catKey.toLowerCase();
  return WORKERS.filter(
    (w) =>
      w.categoryKey.toLowerCase() === k ||
      (w.categories && w.categories.includes(k)) ||
      w.category.toLowerCase().includes(k)
  );
}
